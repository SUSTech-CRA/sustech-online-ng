import { ref } from 'vue'

export function preferredBusLanguage() {
  if (typeof window === 'undefined') return 'zh'
  try {
    const saved = window.localStorage.getItem('sustech-bus-v2-language')
    if (saved === 'zh' || saved === 'en') return saved
  } catch { /* storage may be disabled */ }
  return (window.navigator.languages?.[0] || window.navigator.language || 'zh').toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const busLanguage = ref(preferredBusLanguage())
export const setBusLanguage = (language) => {
  busLanguage.value = language === 'en' ? 'en' : 'zh'
  if (typeof window !== 'undefined') {
    try { window.localStorage.setItem('sustech-bus-v2-language', busLanguage.value) } catch { /* storage may be disabled */ }
  }
}

